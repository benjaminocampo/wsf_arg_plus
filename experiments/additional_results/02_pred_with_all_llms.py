# %%
import pandas as pd

df = pd.read_csv("../../data/wsf_arg_plus_per_claim_all_llms.csv")
# %%
df
# %%
runs = {
	"Mistral-7B": ["zero","one"],
	"Llama-8B": ["zero", "one"],
	"Olmo2-7B": ["zero", "one"],
	"Qwen2.5-7B": ["zero", "one"],
	"Command-r-7B": ["zero", "one"],
	"Mixtral-8x7B": ["zero", "one"],
	"Mistral-22B": ["zero", "one"],
	"Olmo2-32B": ["zero", "one"],
	"Mixtral-8x22B": ["zero", "one"],
	"Llama-70B": ["zero", "one"],
	"Qwen2.5-72B": ["zero", "one"],
	"Command-r-104B": ["zero", "one"],
}
runs = [f"{model_name}_{shot}" for model_name, shots in runs.items() for shot in shots]
# %%
runs
# %% [markdown]
# We encode each of the labels generated by the LLMs using enumeration. "All
# unequal" labels are given the -1 being the case where an LLM produced unstable
# labeling.
# %%
for r in runs:
    df[f"{r}_claim_cw_enc"] = df[f"{r}_claim_cw"].replace({"All unequal": -1, "NFS": 0, "UFS": 1, "CFS": 2})
# %%
X = df[[f"{r}_claim_cw_enc" for r in runs]]

from sklearn.preprocessing import StandardScaler

scaler = StandardScaler()

X_scaled = scaler.fit_transform(X)
# %%
from sklearn.cluster import KMeans

kmeans_scaled = KMeans(n_clusters=3, random_state=0, n_init=10)

df['cluster_kmeans_scaled'] = kmeans_scaled.fit_predict(X_scaled)
