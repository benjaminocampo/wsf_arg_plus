# We calculate the standard deviation and entropy for each claim.
# %%
df["all_llm_std"] = df.apply(lambda row: row[[f"{r}_claim_cw_enc" for r in runs]].std(), axis=1)
# %%
import numpy as np

def entropy_row(row):
    probs = row.value_counts(normalize=True)
    return -(probs * np.log2(probs)).sum()

df["all_llm_entropy"] = df[[f"{r}_claim_cw_enc" for r in runs]].apply(entropy_row, axis=1)
