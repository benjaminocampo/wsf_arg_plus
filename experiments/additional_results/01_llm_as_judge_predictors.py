# %%
from sklearn.cluster import KMeans

kmeans = KMeans(n_clusters=3, random_state=0, n_init=10)
kmeans_scaled = KMeans(n_clusters=3, random_state=0, n_init=10)
kmeans_binary = KMeans(n_clusters=2, random_state=0, n_init=10)
kmeans_binary_scaled = KMeans(n_clusters=2, random_state=0, n_init=10)
df['cluster_kmeans_raw'] = kmeans.fit_predict(X)
